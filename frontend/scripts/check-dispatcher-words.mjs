// Поиск запрещённых слов в собранном бандле вне раздела «Исследование» (критерий F1 №3).
// Запуск после `npm run build`: `npm run check:words`. Чанк ResearchPage-* не проверяется.
// Исключение — утверждённые командой оговорки из списка ALLOWED (отрицание, не утверждение).
import { readdirSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const FORBIDDEN = [
  // «аварийное освещение» — нормативный термин СП 265.1325800.2016 (рекомендация v5); «авария»,
  // «аварийная ситуация», «аварийный выезд» по-прежнему запрещены.
  /вероятност/giu, /авари(?!йн\p{L}*\s+освещени)/giu, /оракул/giu, /recall/giu, /catboost/giu, /фолд/giu,
  /поколени/giu, /корзин/giu, /ввод\s+ПК/giu, /(?<![\p{L}])норма(?![\p{L}])/giu,
  /(?<![\p{L}])исправ(ен|на|но|ны)(?![\p{L}])/giu, /критичн/giu,
  // C0.3: в интерфейсе «линия электропитания», «обесточивание электрооборудования объекта».
  /фидер/giu,
  // F4 (перепроверка F3, 27.09). Только шаблоны с кириллицей: латинские fixture/replay/alarm —
  // имена в собранном коде и дали бы ложные срабатывания.
  /хроническ/giu, /эпизод/giu, /ПК \?/gu, /Режим fixture/gu, /px на/gu, /смоделир/giu,
  /тревог\S* источника/giu, /Сообщения источника/gu,
  // F5: серии проверок — «проверка работоспособности» (ГОСТ Р 59638-2021) и «проверка
  // газоанализаторов»; «опробование» не нормативно, «поверка» — метрологическая процедура.
  // Ответ заказчика 28.09: плановые работы — «ППР» и «ТО»; серии — «похоже на ППР или ТО».
  /опробован/giu, /поверк/giu,
  // Ответ заказчика 28.09: запись с отметкой «тревожное» — «тревожное сообщение СМВУ»; прежние
  // «тревожная запись», «тревога СМВУ», «сейчас в тревоге» и любое «тревога» не используются.
  /тревожн\S*\s+запис/giu, /(?<![\p{L}])тревог/giu,
];
// Утверждённая командой 27.09 формулировка: эмпирическая оценка по уровню карточки,
// калибровка проверена на отложенном периоде. Прочие «вероятности» по-прежнему запрещены.
export const ALLOWED = [
  'Оценка вероятности для карточек этого уровня', 'Оценка вероятности',
  // F5: нормативные названия из СП 265.1325800.2016 в подсказках групп и узлов схемы, не оценка события.
  'АО — аварийное', 'щит аварийного питания',
  // F6: текст записи СМВУ в кавычках (запись «Норма» после тревожной), не оценка состояния.
  '«Норма»',
  // Ответ заказчика 28.09 (технолог, № 10): подписи колокольчика называют аварию в смысле
  // заказчика (угроза жизни людей) и прямо отрицают подтверждение. Больше нигде «авария» нет.
  'по классификации заказчика — аварии', 'это не подтверждённая авария',
];

/** Запрещённые слова текста после удаления утверждённых оговорок: [{ word, index, context }]. */
export function forbiddenWords(source) {
  let text = source;
  for (const phrase of ALLOWED) text = text.split(phrase).join('');
  const found = [];
  for (const pattern of FORBIDDEN) {
    for (const match of text.matchAll(pattern)) {
      const start = Math.max(0, match.index - 40);
      found.push({ word: match[0], index: match.index, context: text.slice(start, match.index + 40).replace(/\s+/g, ' ') });
    }
  }
  return found;
}

// Проверка бандла — только при запуске скрипта (тесты импортируют шаблоны без чтения dist).
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dist = new URL('../dist/assets/', import.meta.url).pathname;
  let problems = 0;
  for (const file of readdirSync(dist).filter((name) => name.endsWith('.js') && !name.startsWith('ResearchPage-'))) {
    for (const item of forbiddenWords(readFileSync(join(dist, file), 'utf8'))) {
      problems += 1;
      console.log(`${file}: «${item.word}» … ${item.context}`);
    }
  }
  if (problems) {
    console.error(`Найдено запрещённых слов вне «Исследования»: ${problems}`);
    process.exit(1);
  }
  console.log('Запрещённых слов вне «Исследования» нет (исключения: ' + ALLOWED.map((item) => `«${item}»`).join(', ') + ').');
}
